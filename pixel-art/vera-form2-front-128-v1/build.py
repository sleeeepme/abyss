# Geometry is evaluated on the native 128 grid, including half-unit vertices.
# Outlines and strings remain ONE native pixel. No 64px bitmap is imported.
def xy(points): return [(round(x*2),round(y*2)) for x,y in points]
def p(points,c): s.polygon(xy(points),C[c])
def l(a,b,c): s.line(*xy([a])[0],*xy([b])[0],C[c])
def r(box,c): s.rect(*(round(v*2) for v in box),C[c])
def shape(points,c):
    p(points,c)
    s.polygon(xy(points),C[0],fill=False)

