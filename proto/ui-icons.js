/* =====================================================================
   UIのアイコン（16×16 のドット絵）
   ---------------------------------------------------------------------
   画面のあちこちで絵文字をアイコン代わりに使っていた（🎒 🗺 🛡 🔨 …）。
   絵文字は端末が持っているフォントで描かれるので、
     ・ドット絵の盤面の横に、なめらかでつるっとした絵が並ぶ
     ・端末ごとに形も色も違う（同じ画面が人によって別物になる）
     ・大きさの基準がフォント任せで、揃えようとしても揃わない
   という三重の問題があった。ここで描き直して、全部こちらの絵にする。

   ---------------------------------------------------------------------
   **描き方（第2版）**

   第1版は line / ell / tri のような「図形を置く道具」で描き、最後に輪郭を
   機械的に太らせていた。これが**ガタガタの原因**だった：
     ・円や斜線の階段の割れ方が図形ごとにばらばらで、左右が揃わない
     ・輪郭を一律に太らせるので、細い所だけ縁に飲まれて形が潰れる
     ・色が「明るい／暗い」の2択で、陰影の段が作れない

   第2版は**1ドットずつ手で置く**。ドット絵はそれ以外に手が無い。
     1) 1枚 = 16行 × 16文字。文字は色の番号（`.` は透明）。
     2) **1番が一番暗い（輪郭）、数字が大きいほど明るい。1枚に6色まで。**
        輪郭も絵の一部なので、物の色を暗くした色にする（真っ黒にしない）。
     3) 光は左上から。上の面を明るく、下の面を暗く。
     4) **左右対称にすべき物は、形（＝透明かどうか）を必ず左右対称にする。**
        `sym` を立てると読み込み時に左半分で右半分を上書きするので、
        手が滑っても形は崩れない。陰影は光の向きがあるので対称でなくてよい。
     5) 太らせる輪郭は使わない。縁は自分で置く。

   持ち物の**中身**（剣・鎧・薬…）は item-icons.js が既にドット絵を持っている。
   そちらと重複させず、ここは「画面の部品」だけを受け持つ
   ——ボタン、見出し、ログに出る記号、職業の印。

   使う側は `<i class="pi pi-bag"></i>` と書くだけ。大きさは font-size に追従。
   盤面（canvas）へは `UI_ICONS.draw(ctx, 名前, x, y, 大きさ)`。
   ===================================================================== */
