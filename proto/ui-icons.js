/* =====================================================================
   UIのアイコン（16×16 のドット絵）
   ---------------------------------------------------------------------
   画面のあちこちで絵文字をアイコン代わりに使っていた（🎒 🗺 🛡 🔨 …）。
   絵文字は端末のフォントで描かれるので、ドット絵の盤面の横でつるっと浮き、
   端末ごとに形も色も違い、大きさも揃わない。ここで全部こちらの絵にする。

   ---------------------------------------------------------------------
   **描き方（第3版）** ——見本シートを実測して決めた規則
   （測った数字と経緯は docs ではなく Project の
     「abyss-UIアイコン-見本の実測と描き方」にある）

     1) 1枚 = 16行 × 16文字。文字は色の番号（`.` は透明）。
     2) **'1' は全アイコン共通の輪郭色 OUT。** 見本の #151528 は明るい地用なので、
        この画面の卓 rgba(22,26,35) に沈まない #302944 まで持ち上げてある。
        輪郭は外周を必ず一周させる（途切れると盤面に溶ける）。
     3) '2' 以降は物の色で、**1枚8色まで（輪郭込み）**。見本の中央値が8色。
        本体の段は4段を目安に、影→光で色相を +15〜25° 回す（影ほど彩度を上げる）。
        同じ明るさの灰色を足すだけの段は作らない——くすんで見える。
     4) 光は左上から。上と左の面を明るく、右下を暗く。
     5) **左右対称にすべき物は、形（＝透明かどうか）を必ず左右対称にする。**
        `sym` を立てると読み込み時に形の食い違いを直して problems に控える。
        陰影は光の向きがあるので対称でなくてよい。
     6) 描く前に「これだと分かる特徴を3つ」言葉で決める（各行の上の注記）。
        描いた後は 13px・24px・白黒・暗い卓の上で見て、3つとも残るか確かめる。

   持ち物の**中身**（剣・鎧・薬…）は item-icons.js が既にドット絵を持っている。
   ここは「画面の部品」だけ——ボタン、見出し、ログの記号、職業の印。

   使う側は `<i class="pi pi-bag"></i>` と書くだけ。大きさは font-size に追従。
   盤面（canvas）へは `UI_ICONS.draw(ctx, 名前, x, y, 大きさ)`。
   ===================================================================== */
