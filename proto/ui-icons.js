'use strict';
const N=16;
const OUT='#302944';   // 全アイコン共通の輪郭

const defs={};
const problems=[];

/* 1枚ぶん登録する。cols は物の色（'2' から）。out で輪郭だけ差し替えられる
   （炎のように、縁まで光っている物だけ）。 */
function I(name, cols, rows, sym, out){
  const pal=[out||OUT].concat(cols);
  if(pal.length>8) problems.push(name+'：色数が'+pal.length+'（8色まで）');
  if(rows.length!==N) problems.push(name+'：行数が'+rows.length);
  const g=[];
  for(let y=0;y<N;y++){
    const r=rows[y]||'';
    if(r.length!==N) problems.push(name+'：'+(y+1)+'行目の長さが'+r.length);
    const line=[];
    for(let x=0;x<N;x++){
      const c=r[x];
      if(!c || c==='.'){ line.push(null); continue; }
      const col=pal[c.charCodeAt(0)-49];            // '1' → 0
      if(!col) problems.push(name+'：'+(y+1)+'行目に無い色 "'+c+'"');
      line.push(col||null);
    }
    g.push(line);
  }
  /* 形だけ左右対称に揃える（陰影は触らない）。
     揃える必要があったということは、描いた升目のほうが食い違っている。
     黙って直すと気づけないので、必ず控えておく。 */
  if(sym){
    const off=[];
    for(let y=0;y<N;y++) for(let x=0;x<N/2;x++){
      const a=g[y][x], b=g[y][N-1-x];
      if(a&&!b){ g[y][N-1-x]=a; off.push((y+1)+'行'+(x+1)+'列'); }
      else if(b&&!a){ g[y][x]=b; off.push((y+1)+'行'+(N-x)+'列'); }
    }
    if(off.length) problems.push(name+'：左右が食い違っていた（'+off.slice(0,4).join('・')+'ほか'+off.length+'箇所）');
  }
  defs[name]={g, sym:!!sym, colors:new Set(g.flat().filter(Boolean)).size};
}

function toURL(g){
  const c=document.createElement('canvas'); c.width=c.height=N;
  const x=c.getContext('2d');
  for(let y=0;y<N;y++)for(let i=0;i<N;i++){ const v=g[y][i]; if(!v) continue;
    x.fillStyle=v; x.fillRect(i,y,1,1); }
  return c.toDataURL();
}

