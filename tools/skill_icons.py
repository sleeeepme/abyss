def preview(out, S=5):
    from PIL import Image, ImageDraw, ImageFont
    try: f=ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc',15,index=0)
    except Exception: f=None
    names=list(ICONS); cw=max(130,15*S+20); ch=15*S+40; cols=9
    rows=(len(names)+cols-1)//cols
    o=Image.new('RGB',(cols*cw+20,rows*ch+20),(20,20,20)); d=ImageDraw.Draw(o)
    for i,n in enumerate(names):
        g=ICONS[n]; x0=10+(i%cols)*cw+(cw-15*S)//2; y0=10+(i//cols)*ch
        for y,r in enumerate(g):
            for x,c in enumerate(r):
                if c=='#': d.rectangle((x0+x*S,y0+y*S,x0+x*S+S-1,y0+y*S+S-1),fill=(242,242,242))
        t=NAMES.get(n,n); tw=d.textlength(t,font=f) if f else 0
        d.text((10+(i%cols)*cw+(cw-tw)/2, y0+15*S+8), t, fill=(160,160,160), font=f)
    o.save(out)

